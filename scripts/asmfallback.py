"""Replace a C/C++ function that does not match yet with its original assembly.

The C body is kept under `#ifdef NONMATCHING`; the `#else` branch gets an mwcc `asm` function
generated by asm2c.py (with an explicit literal pool), preceded by `extern "C"` declarations of the
linker names it uses (mangled C++ names included), so it compiles in a C++ file.

Usage:  python scripts/asmfallback.py <source> <linker name> "<signature as written in the source>"
  e.g.  python scripts/asmfallback.py src/ov003/IslandCamera.cpp _ZN12IslandCamera6SetPosEPK7VecFx32 \\
            "void IslandCamera::SetPos(const VecFx32 *pos)"
"""
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def main():
    src, func, sig = sys.argv[1], sys.argv[2], sys.argv[3]
    path = ROOT / src
    text = path.read_text()
    start = text.index(sig + "\n{")
    end = text.index("\n}\n", start) + 3
    cfunc = text[start:end]
    asm = subprocess.run([sys.executable, str(ROOT / "scripts" / "asm2c.py"), func, sig, "--literal-pool"],
                         cwd=ROOT, capture_output=True, text=True, check=True).stdout
    body = asm[asm.index("{") + 1:asm.rindex("}")]
    funcs = {m.group(1) for m in re.finditer(r"\b(?:bl|blx|b)\s+([A-Za-z_][A-Za-z0-9_]*)", body)}
    datas = {m.group(1) for m in re.finditer(r"\bdcd\s+([A-Za-z_][A-Za-z0-9_]*)", body)} - funcs
    # Declare only names no header declares: mangled C++ names and the compiler's runtime helpers.
    # Branch targets must be declared as functions, literal-pool entries as data.
    keep = re.compile(r"_Z|_f[a-z]|_ll_|_d[a-z]")
    funcs = sorted(n for n in funcs if keep.match(n))
    datas = sorted(n for n in datas if keep.match(n))
    names = funcs + datas
    decl = ""
    if names and src.endswith(".cpp"):
        decl = ('// Linker names used by the asm below.\nextern "C" {\n' +
                "".join(f"void {n}(void);\n" for n in funcs) +
                "".join(f"extern char {n}[];\n" for n in datas) + "}\n")
    new = ("#ifdef NONMATCHING\n" + cfunc + "#else\n" + decl + asm.rstrip() + "\n#endif\n")
    path.write_text(text[:start] + new + text[end:])
    print(f"{func}: replaced ({len(names)} external names)")


if __name__ == "__main__":
    main()
