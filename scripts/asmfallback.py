"""Replace a C/C++ function that does not match yet with its original assembly.

The C body is kept under `#ifdef NONMATCHING`; the `#else` branch gets an mwcc `asm` function
generated by asm2c.py (with an explicit literal pool), preceded by `extern "C"` declarations of the
linker names it uses (mangled C++ names included), so it compiles in a C++ file.

Usage:  python scripts/asmfallback.py <source> <linker name> "<signature as written in the source>" [--overlay N]
  e.g.  python scripts/asmfallback.py src/ov003/IslandCamera.cpp _ZN12IslandCamera6SetPosEPK7VecFx32 \\
            "void IslandCamera::SetPos(const VecFx32 *pos)"
"""
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def module_symbols(overlay):
    """name -> address and address -> name for one overlay's symbols.txt."""
    path = ROOT / "config" / "usa" / "arm9" / "overlays" / f"ov{overlay:03d}" / "symbols.txt"
    by_name, by_addr = {}, {}
    for line in path.read_text().splitlines():
        m = re.match(r"^(\S+) kind:\S+ addr:0x([0-9a-f]+)", line)
        if m:
            by_name[m.group(1)] = int(m.group(2), 16)
            by_addr.setdefault(int(m.group(2), 16), m.group(1))
    return by_name, by_addr


def asm2c(name, sig):
    return subprocess.run([sys.executable, str(ROOT / "scripts" / "asm2c.py"), name, sig, "--literal-pool"],
                          cwd=ROOT, capture_output=True, text=True, check=True).stdout


def main():
    args = sys.argv[1:]
    overlay = None
    if "--overlay" in args:
        i = args.index("--overlay")
        overlay = int(args[i + 1])
        del args[i:i + 2]
    src, func, sig = args[0], args[1], args[2]
    path = ROOT / src
    text = path.read_text()
    start = text.index(sig + "\n{")
    end = text.index("\n}\n", start) + 3
    cfunc = text[start:end]
    asm = asm2c(func, sig)
    if overlay is not None:
        by_name, by_addr = module_symbols(overlay)
        if "\n    " not in asm:
            # The disassembly in build/ may predate a rename: look the function up by its dsd name.
            asm = asm2c(f"func_ov{overlay:03d}_{by_name[func]:08x}", sig)
        # Overlays share addresses, so the disassembly may show another overlay's (or an old) name:
        # map overlay-local dsd names to this overlay's current names.
        asm = re.sub(r"\b(func|data)_ov\d{3}_([0-9a-f]{8})\b",
                     lambda m: by_addr.get(int(m.group(2), 16), m.group(0)), asm)
    if "\n    " not in asm:
        sys.exit(f"{func}: no disassembly found (run build.py, or pass --overlay N)")
    body = asm[asm.index("{") + 1:asm.rindex("}")]
    funcs = {m.group(1) for m in re.finditer(r"\b(?:bl|blx|b)\s+([A-Za-z_][A-Za-z0-9_]*)", body)}
    datas = {m.group(1) for m in re.finditer(r"\bdcd\s+([A-Za-z_][A-Za-z0-9_]*)", body)} - funcs
    # Declare only names no header declares: mangled C++ names and the compiler's runtime helpers.
    # Branch targets must be declared as functions, literal-pool entries as data.
    keep = re.compile(r"_Z|_f[a-z]|_ll_|_d[a-z]")
    funcs = sorted(n for n in funcs if keep.match(n))
    datas = sorted(n for n in datas if keep.match(n))
    names = funcs + datas
    decl = ""
    if names and src.endswith(".cpp"):
        decl = ('// Linker names used by the asm below.\nextern "C" {\n' +
                "".join(f"void {n}(void);\n" for n in funcs) +
                "".join(f"extern char {n}[];\n" for n in datas) + "}\n")
    new = ("#ifdef NONMATCHING\n" + cfunc + "#else\n" + decl + asm.rstrip() + "\n#endif\n")
    path.write_text(text[:start] + new + text[end:])
    print(f"{func}: replaced ({len(names)} external names)")


if __name__ == "__main__":
    main()
